"""Writes hooks/tool-schemas.ts, the tool schemas the mod ships with, from `gpt.py schemas` output.

  python scripts/gpt.py schemas --out schemas.json
  python scripts/ship-schemas.py schemas.json hooks/tool-schemas.ts

The shipped copy keeps each schema's structure (field names, types, required fields, enums) and
leaves out the descriptions, which are Claude Code's own text: at run time the mod reads the full
schemas from the types file on the user's machine, and takes each tool's description from Claude
Code itself. Run this after a Claude Code update.
"""
import json
import sys


def structure(schema):
    """The schema without its `description` texts, at every depth. A field *named* description
    (Bash has one) is a schema, not a text, and stays."""
    if isinstance(schema, dict):
        return {k: structure(v) for k, v in schema.items() if not (k == "description" and isinstance(v, str))}
    if isinstance(schema, list):
        return [structure(v) for v in schema]
    return schema


record = json.load(open(sys.argv[1], encoding="utf-8"))
source = record["source"].replace("\\", "/")
version = source.split("/bundled-skills/")[1].split("/")[0] if "/bundled-skills/" in source else "unknown"
schemas = {name: structure(schema) for name, schema in record["schemas"].items()}
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
    f.write(f"// Generated by `scripts/ship-schemas.py` from the types file of Claude Code {version}:\n")
    f.write("// the structure of each tool's arguments, without Claude Code's own descriptions. The mod\n")
    f.write("// reads the full schemas from the types file on this machine at session start; this copy\n")
    f.write("// is what it falls back to when it finds none.\n\n")
    f.write(f"export const SHIPPED_VERSION = {json.dumps(version)}\n\n")
    f.write("export const SHIPPED_SCHEMAS: Record<string, object> = ")
    f.write(json.dumps(schemas, indent=1, ensure_ascii=False))
    f.write("\n")
print(f"{len(schemas)} tool schemas from Claude Code {version}, structure only, written to {sys.argv[2]}")
